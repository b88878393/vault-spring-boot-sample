-- Notes are stored with their content encrypted by Vault Transit (vault:v<N>:<base64>).
-- Objects are created while the session runs as the shared group role "app_owner" (see
-- spring.datasource.hikari.connection-init-sql), so they are not owned by a short-lived Vault user.
CREATE TABLE notes (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title              VARCHAR(200) NOT NULL,
    content_ciphertext TEXT         NOT NULL,
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT notes_content_is_vault_ciphertext CHECK (content_ciphertext LIKE 'vault:v%')
);
